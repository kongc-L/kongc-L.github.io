function updateNavigationState(requestedPage) {
  const currentHash = window.location.hash || "#top";
  document.querySelectorAll("[data-page-target]").forEach((link) => {
    const isHomeLink = link.dataset.pageTarget === "home";
    link.classList.toggle(
      "active",
      link.dataset.pageTarget === requestedPage && (!isHomeLink || currentHash === "#top"),
    );
  });
  document.querySelectorAll("[data-home-target]").forEach((link) => {
    link.classList.toggle("active", requestedPage === "home" && currentHash === "#" + link.dataset.homeTarget);
  });
}

function setActivePage(pageName, updateUrl = true) {
  const requestedPage = pageName === "workflow" || pageName === "project" ? pageName : "home";
  const currentPage = document.body.dataset.page || "home";
  const currentPanel = pagePanels.find((panel) => panel.dataset.page === currentPage && panel.classList.contains("is-active"));
  const nextPanel = pagePanels.find((panel) => panel.dataset.page === requestedPage);
  if (!nextPanel) return;

  if (currentPage === requestedPage && currentPanel) {
    if (updateUrl && window.location.hash !== "#" + requestedPage) {
      history.replaceState(null, "", requestedPage === "home" ? "#top" : "#" + requestedPage);
    }
    updateNavigationState(requestedPage);
    return;
  }

  document.body.dataset.page = requestedPage;
  const stageHeight = pageStage ? pageStage.getBoundingClientRect().height : 0;
  if (pageStage && stageHeight) pageStage.style.height = stageHeight + "px";

  if (currentPanel) {
    currentPanel.classList.remove("is-active");
    currentPanel.classList.add("is-leaving");
  }
  pagePanels.forEach((panel) => {
    const isActive = panel === nextPanel;
    if (isActive) {
      panel.hidden = false;
      panel.classList.remove("is-leaving");
      panel.classList.add("is-active");
    }
    panel.setAttribute("aria-hidden", String(!isActive));
  });
  window.requestAnimationFrame(() => {
    if (pageStage) {
      pageStage.style.height = getPagePanelHeight(nextPanel) + "px";
    }
  });
  window.setTimeout(() => {
    if (currentPanel) {
      currentPanel.hidden = true;
      currentPanel.classList.remove("is-leaving");
    }
    updatePageStageHeight(nextPanel);
  }, 680);
  window.scrollTo({ top: 0, behavior: "smooth" });
  if (updateUrl) {
    history.pushState(null, "", requestedPage === "home" ? "#top" : "#" + requestedPage);
  }
  updateNavigationState(requestedPage);
}

function initializePageNavigation() {
  const scrollToPageTop = (delay = 0) => {
    window.setTimeout(() => {
      window.scrollTo({ top: 0, behavior: "auto" });
      document.documentElement.scrollTop = 0;
      document.body.scrollTop = 0;
    }, delay);
  };

  const scrollToHomeTarget = (targetId, delay = 0) => {
    window.setTimeout(() => {
      document.getElementById(targetId)?.scrollIntoView({ behavior: "smooth", block: "start" });
    }, delay);
  };

  // Footer BACK TO TOP returns to the currently visible panel instead of switching pages.
  const scrollToActivePageTop = () => {
    const activePage = document.body.dataset.page || "home";
    const pageHash = activePage === "home" ? "#top" : "#" + activePage;
    if (window.location.hash !== pageHash) {
      history.replaceState(null, "", pageHash);
    }
    updateNavigationState(activePage);
    window.scrollTo({ top: 0, behavior: "smooth" });
  };

  let lastScrollY = window.scrollY;
  let scrollFramePending = false;
  const updateTopbarVisibility = () => {
    const currentScrollY = window.scrollY;
    if (topbar) {
      if (currentScrollY <= 8) {
        topbar.classList.remove("is-hidden");
      } else if (!navLinks?.classList.contains("is-visible")) {
        if (currentScrollY > lastScrollY + 4) {
          topbar.classList.add("is-hidden");
        } else if (currentScrollY < lastScrollY - 4) {
          topbar.classList.remove("is-hidden");
        }
      }
    }
    lastScrollY = currentScrollY;
    scrollFramePending = false;
  };

  window.addEventListener("scroll", () => {
    if (scrollFramePending) return;
    scrollFramePending = true;
    window.requestAnimationFrame(updateTopbarVisibility);
  }, { passive: true });
  updateTopbarVisibility();

  const applyHashNavigation = (hashValue, updateUrl = false) => {
    if (hashValue === "workflow" || hashValue === "project") {
      setActivePage(hashValue, updateUrl);
      return;
    }
    if (document.getElementById(hashValue)) {
      setActivePage("home", false);
      scrollToHomeTarget(hashValue, 680);
    }
  };

  document.addEventListener("click", (event) => {
    const pageLink = event.target.closest("[data-page-target]");
    const homeLink = event.target.closest("[data-home-target]");
    const backToTopLink = event.target.closest("[data-back-to-top]");
    if (!pageLink && !homeLink && !backToTopLink) return;
    event.preventDefault();
    if (backToTopLink) {
      scrollToActivePageTop();
    } else if (pageLink) {
      setActivePage(pageLink.dataset.pageTarget);
      if (pageLink.dataset.pageTarget === "home") scrollToPageTop(680);
    } else {
      setActivePage("home", false);
      history.pushState(null, "", "#" + homeLink.dataset.homeTarget);
      updateNavigationState("home");
      scrollToHomeTarget(homeLink.dataset.homeTarget, 680);
    }
    navLinks.classList.remove("is-visible");
    menuButton.setAttribute("aria-expanded", "false");
    portfolioDropdown.classList.remove("is-open");
    portfolioTrigger.setAttribute("aria-expanded", "false");
  });

  window.addEventListener("popstate", () => applyHashNavigation(window.location.hash.slice(1)));
  window.addEventListener("hashchange", () => applyHashNavigation(window.location.hash.slice(1)));
  const initialHash = window.location.hash.slice(1);
  setActivePage(initialHash === "workflow" || initialHash === "project" ? initialHash : "home", false);
  updatePageStageHeight(pagePanels.find((panel) => panel.classList.contains("is-active")));
  if (initialHash && initialHash !== "workflow" && initialHash !== "project" && document.getElementById(initialHash)) {
    if (initialHash === "top") {
      scrollToPageTop(80);
    } else {
      window.setTimeout(() => document.getElementById(initialHash)?.scrollIntoView({ behavior: "smooth", block: "start" }), 80);
    }
  }
}


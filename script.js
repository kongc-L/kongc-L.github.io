function clampLightboxPan(panX = lightboxPanX, panY = lightboxPanY) {
  const mediaWidth = lightboxMedia.clientWidth;
  const mediaHeight = lightboxMedia.clientHeight;
  const naturalWidth = lightboxImage.naturalWidth;
  const naturalHeight = lightboxImage.naturalHeight;
  if (!mediaWidth || !mediaHeight || !naturalWidth || !naturalHeight) {
    return { x: panX, y: panY };
  }

  const containScale = Math.min(mediaWidth / naturalWidth, mediaHeight / naturalHeight);
  const imageWidth = naturalWidth * containScale * lightboxZoom;
  const imageHeight = naturalHeight * containScale * lightboxZoom;
  const dragAllowance = Math.min(mediaWidth, mediaHeight) * 0.08;
  const maxPanX = Math.max(0, (imageWidth - mediaWidth) / 2) + dragAllowance;
  const maxPanY = Math.max(0, (imageHeight - mediaHeight) / 2) + dragAllowance;
  return {
    x: Math.max(-maxPanX, Math.min(maxPanX, panX)),
    y: Math.max(-maxPanY, Math.min(maxPanY, panY)),
  };
}

function applyLightboxTransform() {
  const mediaWidth = lightboxMedia.clientWidth;
  const mediaHeight = lightboxMedia.clientHeight;
  const naturalWidth = lightboxImage.naturalWidth;
  const naturalHeight = lightboxImage.naturalHeight;
  if (mediaWidth && mediaHeight && naturalWidth && naturalHeight) {
    const containScale = Math.min(mediaWidth / naturalWidth, mediaHeight / naturalHeight);
    lightboxImage.style.width = naturalWidth * containScale + "px";
    lightboxImage.style.height = naturalHeight * containScale + "px";
  }
  const pan = clampLightboxPan();
  lightboxPanX = pan.x;
  lightboxPanY = pan.y;
  lightboxImage.style.transform =
    "translate3d(" + lightboxPanX + "px, " + lightboxPanY + "px, 0) scale(" + lightboxZoom + ")";
}

function setLightboxPan(nextPanX, nextPanY) {
  const pan = clampLightboxPan(nextPanX, nextPanY);
  lightboxPanX = pan.x;
  lightboxPanY = pan.y;
  applyLightboxTransform();
}

function updateLightboxZoom(nextZoom, resetPan = false) {
  lightboxZoom = Math.max(0.5, Math.min(3, nextZoom));
  if (resetPan) {
    lightboxPanX = 0;
    lightboxPanY = 0;
  }
  applyLightboxTransform();
  zoomResetButton.textContent = Math.round(lightboxZoom * 100) + "%";
}

function renderArtwork(index) {
  if (!activeLightboxItems.length) return;
  currentIndex = (index + activeLightboxItems.length) % activeLightboxItems.length;
  const artwork = activeLightboxItems[currentIndex];
  updateLightboxZoom(1, true);
  lightboxImage.src = artwork.image;
  lightboxImage.alt = artwork.alt;
  lightboxKicker.textContent = artwork.kicker;
  lightboxTitle.textContent = artwork.title;
  lightboxDescription.textContent = artwork.description;
  lightboxCount.textContent = String(currentIndex + 1).padStart(2, "0") + " / " + String(activeLightboxItems.length).padStart(2, "0");
  lightboxModel.textContent = artwork.model || "";
  lightboxExtra.textContent = artwork.extra || "";
  lightboxModelRow.classList.toggle("is-empty", !artwork.model);
  lightboxExtraRow.classList.toggle("is-empty", !artwork.extra);
}

